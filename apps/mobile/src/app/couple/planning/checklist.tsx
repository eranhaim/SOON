import Feather from '@expo/vector-icons/Feather';
import { useState } from 'react';
import { Pressable, StyleSheet, View } from 'react-native';

import { CHECKLIST_TEMPLATES, checklistPhaseFor, daysBetween, todayIso, type TaskDTO } from '@soon/shared';

import { Button } from '@/components/Button';
import { DateField } from '@/components/DateField';
import { Loading, Screen } from '@/components/Screen';
import { Sheet } from '@/components/Sheet';
import { Text } from '@/components/Text';
import { TextField } from '@/components/TextField';
import { Chip, ChipGroup, IconButton, SectionTitle } from '@/components/ui';
import { errorMessage } from '@/lib/api';
import { confirm } from '@/lib/confirm';
import { formatDayShort } from '@/lib/dates';
import { keys, useApiMutation, useApiQuery } from '@/lib/query';
import { useOwnWedding } from '@/lib/wedding';
import { colors, hairline, space } from '@/theme/tokens';

type Draft = { id?: string; title: string; notes: string; dueDate: string | null };
const TEMPLATE_DAYS = new Map(CHECKLIST_TEMPLATES.map((t) => [t.key, t.daysBefore]));

/** Checklist (spec §7.1): auto-generated by wedding date; add, edit, delete, complete. */
export default function Checklist() {
  const wedding = useOwnWedding();
  const q = useApiQuery<TaskDTO[]>(keys.tasks, '/api/planning/tasks');
  const m = useApiMutation<TaskDTO[]>({ setData: keys.tasks, invalidate: [keys.home] });
  const [filter, setFilter] = useState<'open' | 'done' | 'all'>('open');
  const [draft, setDraft] = useState<Draft | null>(null);
  const [error, setError] = useState<string>();

  if (q.isPending) return <Loading />;
  const tasks = q.data ?? [];
  const done = tasks.filter((t) => t.doneAt).length;
  const pct = tasks.length ? Math.round((done / tasks.length) * 100) : 0;
  const today = todayIso();
  const shown = tasks.filter((t) => (filter === 'all' ? true : filter === 'done' ? t.doneAt : !t.doneAt));

  // Group by planning phase (days before the wedding), custom tasks by their own due date.
  const groups = new Map<string, TaskDTO[]>();
  for (const t of shown) {
    const days =
      t.templateKey && TEMPLATE_DAYS.has(t.templateKey)
        ? TEMPLATE_DAYS.get(t.templateKey)!
        : t.dueDate && wedding.weddingDate
          ? daysBetween(t.dueDate, wedding.weddingDate)
          : null;
    const label = days == null ? 'ללא תאריך' : checklistPhaseFor(days).label;
    groups.set(label, [...(groups.get(label) ?? []), t]);
  }

  async function save() {
    if (!draft || !draft.title.trim()) return setError('נא לכתוב משימה');
    setError(undefined);
    try {
      const json = { title: draft.title, notes: draft.notes.trim() || null, dueDate: draft.dueDate };
      await m.mutateAsync(draft.id ? { path: `/api/planning/tasks/${draft.id}`, method: 'PATCH', json } : { path: '/api/planning/tasks', json });
      setDraft(null);
    } catch (err) {
      setError(errorMessage(err));
    }
  }

  return (
    <Screen
      title="משימות"
      back
      backTo="/couple/planning"
      right={<IconButton icon="plus" label="משימה חדשה" onPress={() => setDraft({ title: '', notes: '', dueDate: null })} />}>
      <View style={{ gap: space.sm }}>
        <Text variant="bodySmall" color={colors.inkSoft}>{`${done} מתוך ${tasks.length} בוצעו · ${pct}%`}</Text>
        <View style={styles.bar}>
          <View style={[styles.barFill, { width: `${pct}%` }]} />
        </View>
      </View>
      <ChipGroup>
        <Chip label="פתוחות" selected={filter === 'open'} onPress={() => setFilter('open')} />
        <Chip label="בוצעו" selected={filter === 'done'} onPress={() => setFilter('done')} />
        <Chip label="הכל" selected={filter === 'all'} onPress={() => setFilter('all')} />
      </ChipGroup>

      {[...groups.entries()].map(([label, list]) => (
        <View key={label}>
          <SectionTitle>{label}</SectionTitle>
          {list.map((t) => {
            const overdue = !t.doneAt && t.dueDate != null && t.dueDate < today;
            return (
              <View key={t.id} style={styles.row}>
                <Pressable
                  accessibilityRole="checkbox"
                  accessibilityState={{ checked: Boolean(t.doneAt) }}
                  accessibilityLabel={t.title}
                  hitSlop={8}
                  onPress={() => m.mutate({ path: `/api/planning/tasks/${t.id}`, method: 'PATCH', json: { done: !t.doneAt } })}
                  style={[styles.check, t.doneAt && styles.checkOn]}>
                  {t.doneAt ? <Feather name="check" size={14} color={colors.inverse} /> : null}
                </Pressable>
                <Pressable style={{ flex: 1, gap: 2 }} onPress={() => setDraft({ id: t.id, title: t.title, notes: t.notes ?? '', dueDate: t.dueDate })}>
                  <Text variant="body" color={t.doneAt ? colors.inkMuted : colors.ink} style={t.doneAt ? styles.strike : undefined}>
                    {t.title}
                  </Text>
                  {t.dueDate ? (
                    <Text variant="caption" color={overdue ? colors.danger : colors.inkMuted}>
                      {overdue ? `באיחור · ${formatDayShort(t.dueDate)}` : formatDayShort(t.dueDate)}
                    </Text>
                  ) : null}
                </Pressable>
              </View>
            );
          })}
        </View>
      ))}
      {!shown.length ? (
        <Text color={colors.inkSoft} align="center">
          {filter === 'open' ? 'אין משימות פתוחות. כל הכבוד!' : 'אין משימות להצגה.'}
        </Text>
      ) : null}

      <Sheet
        visible={draft != null}
        onClose={() => setDraft(null)}
        title={draft?.id ? 'עריכת משימה' : 'משימה חדשה'}
        footer={
          <>
            {draft?.id ? (
              <Button
                variant="ghost"
                label="מחיקה"
                style={{ flex: 1 }}
                onPress={async () => {
                  if (!(await confirm('מחיקת משימה', draft.title, 'מחיקה'))) return;
                  await m.mutateAsync({ path: `/api/planning/tasks/${draft.id}`, method: 'DELETE' });
                  setDraft(null);
                }}
              />
            ) : null}
            <Button label="שמירה" loading={m.isPending} style={{ flex: 2 }} onPress={save} />
          </>
        }>
        {draft ? (
          <>
            <TextField label="משימה" value={draft.title} onChangeText={(title) => setDraft({ ...draft, title })} maxLength={200} />
            <DateField label="תאריך יעד" value={draft.dueDate} onChange={(dueDate) => setDraft({ ...draft, dueDate })} clearable />
            <TextField label="הערות" value={draft.notes} onChangeText={(notes) => setDraft({ ...draft, notes })} multiline style={{ minHeight: 80 }} />
            {error ? <Text variant="bodySmall" color={colors.danger}>{error}</Text> : null}
          </>
        ) : null}
      </Sheet>
    </Screen>
  );
}

const styles = StyleSheet.create({
  bar: { height: 3, backgroundColor: colors.line },
  barFill: { height: 4, borderRadius: 2, backgroundColor: colors.accent },
  row: { flexDirection: 'row', alignItems: 'center', gap: space.md, paddingVertical: space.md, borderBottomWidth: hairline, borderBottomColor: colors.line },
  check: { width: 22, height: 22, borderRadius: 11, borderWidth: 1, borderColor: colors.stoneDeep, alignItems: 'center', justifyContent: 'center' },
  checkOn: { backgroundColor: colors.accent, borderColor: colors.accent },
  strike: { textDecorationLine: 'line-through' },
});
